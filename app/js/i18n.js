// UI strings, Russian and English. Functions are plural forms or strings that take a value.
const plural = (n, one, few, many) => {
  const m = n % 10,
    h = n % 100;
  return m === 1 && h !== 11 ? one : m >= 2 && m <= 4 && (h < 12 || h > 14) ? few : many;
};

